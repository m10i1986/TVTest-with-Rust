/// CRC16 を計算する。CRC.cpp:78。
/// 初期値 0xFFFF、多項式 0x8005。
pub fn crc16(data: &[u8], init: u16) -> u16 {
    let mut crc = init;
    for &b in data {
        crc = (crc << 8) ^ CRC16_TABLE[((crc >> 8) as u8 ^ b) as usize];
    }
    crc
}

/// CRC16-CCITT を計算する。CRC.cpp:127。
/// 初期値 0xFFFF、多項式 0x1021。
pub fn crc16_ccitt(data: &[u8], init: u16) -> u16 {
    let mut crc = init;
    for &b in data {
        crc = (crc << 8) ^ CRC16_CCITT_TABLE[((crc >> 8) as u8 ^ b) as usize];
    }
    crc
}

/// CRC32(IEEE 802.3)を計算する。CRC.cpp:176。
/// 初期値 0xFFFFFFFF、結果は反転。
pub fn crc32(data: &[u8], init: u32) -> u32 {
    let mut crc = !init;
    for &b in data {
        crc = (crc >> 8) ^ CRC32_TABLE[((crc as u8) ^ b) as usize];
    }
    !crc
}

/// CRC32-MPEG2 を計算する。CRC.cpp:267。
/// 初期値 0xFFFFFFFF、多項式 0x04C11DB7。
pub fn crc32_mpeg2(data: &[u8], init: u32) -> u32 {
    let mut crc = init;
    for &b in data {
        crc = (crc << 8) ^ CRC32_MPEG2_TABLE[((crc >> 24) as u8 ^ b) as usize];
    }
    crc
}

